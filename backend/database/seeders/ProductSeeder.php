    private function uniqueSlug(string $name): string
    {
        $slug     = Str::slug($name);
        if (!$slug) $slug = 'product-' . uniqid();
        $original = $slug;
        $i        = 1;

        while (Product::where('slug', $slug)->exists()) {
            $slug = "{$original}-{$i}";
            $i++;
        }

        return $slug;
    }
